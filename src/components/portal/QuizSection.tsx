import React, { useEffect, useState } from 'react';
import { apiJson } from '../../utils/api';
import { parseQuizImport, AI_PROMPT_TEMPLATE } from '../../utils/quizImport';

type Role = 'student' | 'tutor' | 'admin';

const card = 'p-5 rounded-3xl bg-[#140b33] border border-indigo-900/60 space-y-3';
const inp = 'bg-slate-900 border border-violet-500/30 text-white rounded-lg px-3 py-2 text-sm focus:outline-none focus:border-amber-400 w-full';
const btn = 'rounded-lg bg-amber-400 text-slate-950 font-bold text-xs px-3 py-2 disabled:opacity-50';
const btn2 = 'rounded-lg bg-slate-800 border border-slate-600 text-xs px-3 py-2 text-white disabled:opacity-50';
const when = (d: any) => (d ? new Date(d).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' }) : '-');

interface DraftQ { question: string; options: string[]; correct: number }
const emptyQ = (): DraftQ => ({ question: '', options: ['', '', '', ''], correct: 0 });

export const QuizSection: React.FC<{ role: Role }> = ({ role }) => {
  const isStudent = role === 'student';
  const [quizzes, setQuizzes] = useState<any[]>([]);
  const [students, setStudents] = useState<{ id: number; name: string }[]>([]);
  const [loading, setLoading] = useState(true);
  const [msg, setMsg] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);

  // staff: create form
  const [showCreate, setShowCreate] = useState(false);
  const [saving, setSaving] = useState(false);
  const [title, setTitle] = useState('');
  const [qs, setQs] = useState<DraftQ[]>([emptyQ()]);
  const [createIds, setCreateIds] = useState<number[]>([]);
  const [createDue, setCreateDue] = useState('');

  // staff: bulk import (JSON / text generated by an AI tool)
  const [showImport, setShowImport] = useState(true);
  const [importText, setImportText] = useState('');
  const [importErrors, setImportErrors] = useState<string[]>([]);
  const [promptCopied, setPromptCopied] = useState(false);

  // staff: assign / results panels
  const [assignFor, setAssignFor] = useState<number | null>(null);
  const [assignIds, setAssignIds] = useState<number[]>([]);
  const [assignDue, setAssignDue] = useState('');
  const [resultsFor, setResultsFor] = useState<number | null>(null);
  const [results, setResults] = useState<any[]>([]);

  // student: taking a quiz
  const [taking, setTaking] = useState<any | null>(null);
  const [takeQs, setTakeQs] = useState<any[]>([]);
  const [answers, setAnswers] = useState<Record<number, number>>({});
  const [outcome, setOutcome] = useState<{ score: number; correct: number; total: number; review: any[]; answers_saved?: boolean } | null>(null);

  const load = async () => {
    try {
      setQuizzes(await apiJson<any[]>('/api/quizzes'));
      if (!isStudent) {
        if (role === 'admin') {
          const u = await apiJson<any[]>('/api/users?role=student');
          setStudents(u.filter(x => x.active !== 0).map(x => ({ id: x.id, name: x.name })));
        } else {
          const e = await apiJson<any[]>('/api/enrollments');
          const map = new Map<number, string>();
          e.forEach(x => map.set(x.student_id, x.student_name));
          setStudents([...map].map(([id, name]) => ({ id, name })));
        }
      }
    } catch (e: any) { setErr(e.message); }
    setLoading(false);
  };
  useEffect(() => { load(); }, []);

  const toggle = (list: number[], set: (v: number[]) => void, id: number) =>
    set(list.includes(id) ? list.filter(x => x !== id) : [...list, id]);

  const iso = (v: string) => (v ? new Date(v).toISOString() : null);

  const createQuiz = async (e: React.FormEvent) => {
    e.preventDefault(); setErr(null); setMsg(null);
    // keep only questions that are filled in; keep original option positions for the correct index
    const filled = qs.filter(q => q.question.trim());
    if (!title.trim()) return setErr('Quiz title likho.');
    if (!filled.length) return setErr('Kam se kam 1 question add karo.');
    for (let i = 0; i < filled.length; i++) {
      const q = filled[i];
      if (q.options.filter(o => o.trim()).length < 2) return setErr(`Question ${i + 1}: kam se kam 2 options chahiye.`);
      if (!q.options[q.correct]?.trim()) return setErr(`Question ${i + 1}: sahi answer ka option khali hai.`);
    }
    setSaving(true);
    try {
      const r = await apiJson('/api/quizzes', { method: 'POST', body: JSON.stringify({
        title: title.trim(), student_ids: createIds, due_at: iso(createDue),
        questions: filled.map(q => ({
          question: q.question.trim(),
          options: q.options.filter(o => o.trim()),
          correct_option_index: q.options.slice(0, q.correct).filter(o => o.trim()).length
        }))
      }) });
      setMsg(`Quiz created${r.assigned ? ` and assigned to ${r.assigned} student(s)` : ''}.`);
      setTitle(''); setQs([emptyQ()]); setCreateIds([]); setCreateDue(''); setShowCreate(false);
      await load();
    } catch (e: any) { setErr(e.message); }
    setSaving(false);
  };

  const copyPrompt = () => {
    navigator.clipboard?.writeText(AI_PROMPT_TEMPLATE);
    setPromptCopied(true); setTimeout(() => setPromptCopied(false), 2000);
  };

  const applyImport = (text: string = importText) => {
    const r = parseQuizImport(text);
    setImportErrors(r.errors);
    if (!r.questions.length) return;
    const drafts: DraftQ[] = r.questions.map(q => ({
      question: q.question,
      options: [...q.options, ...Array(Math.max(0, 4 - q.options.length)).fill('')],
      correct: q.correct
    }));
    const hasManual = qs.some(q => q.question.trim());
    setQs(hasManual ? [...qs.filter(q => q.question.trim()), ...drafts] : drafts);
    if (r.title && !title.trim()) setTitle(r.title);
    setMsg(`${drafts.length} question(s) imported${r.errors.length ? `, ${r.errors.length} skipped` : ''}. Review them below, then create the quiz.`);
    if (!r.errors.length) { setImportText(''); setShowImport(false); }
  };

  const doAssign = async (id: number) => {
    setErr(null); setMsg(null);
    try {
      const r = await apiJson(`/api/quizzes/${id}/assign`, { method: 'POST', body: JSON.stringify({ student_ids: assignIds, due_at: iso(assignDue) }) });
      setMsg(`Assigned to ${r.assigned} student(s).`);
      setAssignFor(null); setAssignIds([]); setAssignDue('');
      await load();
    } catch (e: any) { setErr(e.message); }
  };

  const showResults = async (id: number) => {
    if (resultsFor === id) { setResultsFor(null); return; }
    setErr(null);
    try { setResults(await apiJson<any[]>(`/api/quizzes/${id}/results`)); setResultsFor(id); setAssignFor(null); }
    catch (e: any) { setErr(e.message); }
  };

  // admin only: delete a whole quiz, or one student's result (so they can retake)
  const deleteQuiz = async (q: any) => {
    if (!window.confirm(`Delete quiz "${q.title}" with all its questions, assignments and results?`)) return;
    setErr(null); setMsg(null);
    try { await apiJson(`/api/admin/records/quizzes/${q.id}`, { method: 'DELETE' }); setMsg('Quiz deleted.'); setResultsFor(null); setAssignFor(null); await load(); }
    catch (e: any) { setErr(e.message); }
  };
  const deleteResult = async (quizId: number, studentId: number, name: string) => {
    if (!window.confirm(`Delete ${name}'s result? The student will be able to take this quiz again.`)) return;
    setErr(null); setMsg(null);
    try {
      await apiJson(`/api/admin/quizzes/${quizId}/results/${studentId}`, { method: 'DELETE' });
      setMsg('Result deleted.');
      setResults(await apiJson<any[]>(`/api/quizzes/${quizId}/results`));
      await load();
    } catch (e: any) { setErr(e.message); }
  };

  const startQuiz = async (q: any) => {
    setErr(null); setMsg(null); setOutcome(null); setAnswers({});
    try {
      const rows = await apiJson<any[]>(`/api/quizzes/${q.id}/questions`);
      setTakeQs(rows.map(r => ({ ...r, options: typeof r.options === 'string' ? JSON.parse(r.options) : r.options })));
      setTaking(q);
    } catch (e: any) { setErr(e.message); }
  };

  // Re-open an already submitted quiz to see answers + correct answers
  const viewResult = async (q: any) => {
    setErr(null); setMsg(null); setAnswers({});
    try {
      const r = await apiJson<any>(`/api/quizzes/${q.id}/review`);
      setOutcome({ score: r.score, correct: r.correct, total: r.total, review: r.review || [], answers_saved: r.answers_saved });
      setTakeQs([]);
      setTaking(q);
    } catch (e: any) { setErr(e.message); }
  };

  const submitQuiz = async () => {
    setErr(null);
    try {
      const r = await apiJson(`/api/quizzes/${taking.id}/submit`, { method: 'POST', body: JSON.stringify({ answers }) });
      setOutcome({ score: r.score, correct: r.correct, total: r.total, review: r.review || [] });
      await load();
    } catch (e: any) { setErr(e.message); }
  };

  const picker = (ids: number[], set: (v: number[]) => void) => (
    <div className="space-y-1">
      <div className="text-xs text-slate-300 font-bold">Assign to students {students.length === 0 && <span className="text-slate-500 font-normal">(no students available)</span>}</div>
      <div className="flex flex-wrap gap-2 max-h-32 overflow-y-auto">
        {students.map(s => (
          <label key={s.id} className={`px-2.5 py-1 rounded-lg border text-xs cursor-pointer ${ids.includes(s.id) ? 'bg-amber-400 text-slate-950 border-amber-400 font-bold' : 'bg-slate-900 border-violet-500/30 text-slate-200'}`}>
            <input type="checkbox" className="hidden" checked={ids.includes(s.id)} onChange={() => toggle(ids, set, s.id)} />
            {s.name}
          </label>
        ))}
      </div>
    </div>
  );

  if (loading) return <div className="text-slate-300 text-sm py-6 text-center">Loading quizzes...</div>;

  // ---------------- Student view ----------------
  if (isStudent) {
    if (taking) {
      return (
        <div className={card}>
          <div className="flex items-center justify-between gap-2">
            <h3 className="font-bold text-white">{taking.title}</h3>
            <button className={btn2} onClick={() => { setTaking(null); setOutcome(null); }}>Back</button>
          </div>
          {err && <div className="text-sm text-red-300 bg-red-950/50 border border-red-800/60 rounded-lg px-3 py-2">{err}</div>}
          {outcome ? (
            <div className="space-y-3">
              <div className="p-4 rounded-xl bg-emerald-950/50 border border-emerald-700/60 text-center space-y-1">
                <div className="text-3xl font-black text-emerald-300">{outcome.score}%</div>
                <div className="text-sm text-slate-200">{outcome.correct} of {outcome.total} correct</div>
              </div>
              {outcome.review.length > 0 && <div className="text-xs text-slate-300 font-bold">Your answers</div>}
              {outcome.answers_saved === false && (
                <div className="text-[11px] text-amber-300">Your chosen answers were not saved for this older attempt. Correct answers are shown below.</div>
              )}
              {outcome.review.map((r: any, i: number) => (
                <div key={r.id} className={`p-3 rounded-xl border space-y-2 text-sm ${r.is_correct ? 'bg-emerald-950/30 border-emerald-700/50' : 'bg-red-950/30 border-red-800/50'}`}>
                  <div className="flex items-start justify-between gap-2">
                    <div className="font-semibold text-white">{i + 1}. {r.question}</div>
                    <span className={`text-[11px] font-bold shrink-0 ${r.is_correct ? 'text-emerald-300' : 'text-red-300'}`}>
                      {r.is_correct ? '\u2713 Correct' : r.selected_index === null ? 'Not answered' : '\u2717 Wrong'}
                    </span>
                  </div>
                  {r.options.map((o: string, oi: number) => {
                    const isRight = oi === r.correct_index;
                    const isPicked = oi === r.selected_index;
                    const cls = isRight
                      ? 'border-emerald-400 bg-emerald-500/15 text-emerald-100'
                      : isPicked ? 'border-red-400 bg-red-500/15 text-red-100' : 'border-slate-700 text-slate-400';
                    return (
                      <div key={oi} className={`flex items-center justify-between gap-2 px-3 py-2 rounded-lg border text-xs ${cls}`}>
                        <span>{o}</span>
                        <span className="text-[10px] font-bold shrink-0">
                          {isRight && isPicked ? 'Your answer \u2713' : isRight ? 'Correct answer' : isPicked ? 'Your answer' : ''}
                        </span>
                      </div>
                    );
                  })}
                </div>
              ))}
            </div>
          ) : (
            <>
              {takeQs.map((q, i) => (
                <div key={q.id} className="p-3 rounded-xl bg-[#1a0f40] border border-indigo-800/50 space-y-2 text-sm">
                  <div className="font-semibold text-white">{i + 1}. {q.question}</div>
                  {q.options.map((o: string, oi: number) => (
                    <label key={oi} className={`flex items-center gap-2 px-3 py-2 rounded-lg border cursor-pointer text-xs ${answers[q.id] === oi ? 'border-amber-400 bg-amber-400/10 text-white' : 'border-slate-700 text-slate-300'}`}>
                      <input type="radio" name={`q${q.id}`} checked={answers[q.id] === oi} onChange={() => setAnswers({ ...answers, [q.id]: oi })} />
                      {o}
                    </label>
                  ))}
                </div>
              ))}
              <button className={btn} disabled={Object.keys(answers).length < takeQs.length} onClick={submitQuiz}>
                Submit quiz ({Object.keys(answers).length}/{takeQs.length} answered)
              </button>
              <p className="text-[11px] text-slate-500">You can submit a quiz only once.</p>
            </>
          )}
        </div>
      );
    }
    return (
      <div className={card}>
        <h3 className="font-bold text-white">Quizzes ({quizzes.length})</h3>
        {msg && <div className="text-sm text-emerald-300">{msg}</div>}
        {err && <div className="text-sm text-red-300">{err}</div>}
        {quizzes.length === 0 && <p className="text-xs text-slate-400">No quiz assigned yet.</p>}
        {quizzes.map(q => {
          const done = q.score !== null && q.score !== undefined;
          return (
            <div key={q.id} className="p-3 rounded-xl bg-[#1a0f40] border border-indigo-800/50 text-xs flex flex-wrap items-center justify-between gap-2">
              <div>
                <div className="font-bold text-white text-sm">{q.title}</div>
                <div className="text-slate-400">{q.question_count} questions &bull; by {q.assigned_by_name}{q.due_at ? ` \u2022 due ${when(q.due_at)}` : ''}</div>
              </div>
              {done
                ? <div className="flex items-center gap-2"><div className="text-emerald-300 font-bold">Score: {Number(q.score)}%</div><button className={btn2} onClick={() => viewResult(q)}>View answers</button></div>
                : <button className={btn} onClick={() => startQuiz(q)}>Start quiz</button>}
            </div>
          );
        })}
      </div>
    );
  }

  // ---------------- Tutor / Admin view ----------------
  return (
    <div className={card}>
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 className="font-bold text-white">Quizzes ({quizzes.length})</h3>
        <button className={btn} onClick={() => setShowCreate(!showCreate)}>{showCreate ? 'Close' : '+ Create quiz'}</button>
      </div>
      {msg && <div className="text-sm text-emerald-300 bg-emerald-950/50 border border-emerald-800/60 rounded-lg px-3 py-2">{msg}</div>}
      {err && <div className="text-sm text-red-300 bg-red-950/50 border border-red-800/60 rounded-lg px-3 py-2">{err}</div>}

      {showCreate && (
        <form noValidate onSubmit={createQuiz} className="p-3 rounded-xl bg-[#1a0f40] border border-indigo-800/50 space-y-3">
          <input className={inp} placeholder="Quiz title" value={title} onChange={e => setTitle(e.target.value)} />

          <div className="p-3 rounded-lg bg-[#140b33] border border-amber-400/30 space-y-2">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="text-xs text-slate-200"><strong className="text-amber-300">Bulk import</strong> — paste 20–30 questions generated by an AI tool instead of typing them one by one.</div>
              <button type="button" className={btn2} onClick={() => setShowImport(!showImport)}>{showImport ? 'Hide import' : 'Import questions'}</button>
            </div>
            {showImport && (
              <div className="space-y-2">
                <div className="text-[11px] text-slate-400">
                  1) Click "Copy AI prompt". 2) Paste it in any AI tool (ChatGPT, Gemini, Claude) and fill topic, class and number of questions. 3) Paste the AI answer in the box below. Questions are added automatically.
                </div>
                <div className="flex flex-wrap gap-2">
                  <button type="button" className={btn2} onClick={copyPrompt}>{promptCopied ? 'Copied' : 'Copy AI prompt (format)'}</button>
                </div>
                <pre className="text-[10px] leading-snug text-slate-400 bg-slate-950 border border-slate-800 rounded-lg p-2 max-h-28 overflow-auto whitespace-pre-wrap">{AI_PROMPT_TEMPLATE}</pre>
                <textarea className={inp + ' font-mono text-xs'} rows={8} placeholder="Paste the AI answer here" value={importText} onChange={e => setImportText(e.target.value)}
                  onPaste={e => { const t = e.clipboardData.getData('text'); if (t.trim()) { setImportText(t); setTimeout(() => applyImport(t), 0); } }} />
                {importErrors.length > 0 && (
                  <ul className="text-xs text-red-300 bg-red-950/50 border border-red-800/60 rounded-lg px-3 py-2 list-disc list-inside space-y-0.5 max-h-28 overflow-auto">
                    {importErrors.map((e, i) => <li key={i}>{e}</li>)}
                  </ul>
                )}
                <button type="button" className={btn} disabled={!importText.trim()} onClick={() => applyImport()}>Import into this quiz</button>
              </div>
            )}
          </div>

          {qs.map((q, qi) => (
            <div key={qi} className="p-3 rounded-lg bg-[#140b33] border border-indigo-900/60 space-y-2">
              <div className="flex gap-2">
                <input className={inp} placeholder={`Question ${qi + 1}`} value={q.question} onChange={e => setQs(qs.map((x, i) => i === qi ? { ...x, question: e.target.value } : x))} />
                {qs.length > 1 && <button type="button" className={btn2} onClick={() => setQs(qs.filter((_, i) => i !== qi))}>Remove</button>}
              </div>
              {q.options.map((o, oi) => (
                <div key={oi} className="flex items-center gap-2">
                  <input type="radio" name={`correct${qi}`} checked={q.correct === oi} onChange={() => setQs(qs.map((x, i) => i === qi ? { ...x, correct: oi } : x))} title="Correct answer" />
                  <input className={inp} placeholder={`Option ${oi + 1}${oi < 2 ? '' : ' (optional)'}`} value={o}
                    onChange={e => setQs(qs.map((x, i) => i === qi ? { ...x, options: x.options.map((y, j) => j === oi ? e.target.value : y) } : x))} />
                </div>
              ))}
              <div className="text-[11px] text-slate-500">Select the radio button next to the correct option.</div>
            </div>
          ))}
          <button type="button" className={btn2} onClick={() => setQs([...qs, emptyQ()])}>+ Add question</button>
          {picker(createIds, setCreateIds)}
          <div className="flex flex-wrap items-center gap-2">
            <label className="text-xs text-slate-300">Due (optional)</label>
            <input type="datetime-local" className={inp + ' !w-auto'} value={createDue} onChange={e => setCreateDue(e.target.value)} />
          </div>
          {err && <div className="text-sm text-red-300 bg-red-950/50 border border-red-800/60 rounded-lg px-3 py-2">{err}</div>}
          <button className={btn} type="submit" disabled={saving}>{saving ? 'Saving...' : `Create quiz${createIds.length ? ` & assign to ${createIds.length}` : ''}`}</button>
        </form>
      )}

      {quizzes.length === 0 && <p className="text-xs text-slate-400">No quizzes yet. Create the first one.</p>}
      {quizzes.map(q => (
        <div key={q.id} className="p-3 rounded-xl bg-[#1a0f40] border border-indigo-800/50 text-xs space-y-2">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div>
              <div className="font-bold text-white text-sm">{q.title}</div>
              <div className="text-slate-400">{q.question_count} questions &bull; {q.assigned_count} assigned &bull; {q.attempted_count} attempted &bull; by {q.created_by_name}</div>
            </div>
            <div className="flex gap-2">
              <button className={btn} onClick={() => { setAssignFor(assignFor === q.id ? null : q.id); setResultsFor(null); setAssignIds([]); }}>Assign</button>
              <button className={btn2} onClick={() => showResults(q.id)}>Results</button>
              {role === 'admin' && <button className="rounded-lg bg-red-600 text-white font-bold text-xs px-3 py-2" onClick={() => deleteQuiz(q)}>Delete</button>}
            </div>
          </div>
          {assignFor === q.id && (
            <div className="space-y-2 pt-1">
              {picker(assignIds, setAssignIds)}
              <div className="flex flex-wrap items-center gap-2">
                <label className="text-slate-300">Due (optional)</label>
                <input type="datetime-local" className={inp + ' !w-auto'} value={assignDue} onChange={e => setAssignDue(e.target.value)} />
                <button className={btn} disabled={!assignIds.length} onClick={() => doAssign(q.id)}>Assign to {assignIds.length || ''} selected</button>
              </div>
            </div>
          )}
          {resultsFor === q.id && (
            <div className="pt-1 space-y-1">
              {results.length === 0 && <div className="text-slate-400">Not assigned to any student yet.</div>}
              {results.map(r => (
                <div key={r.student_id} className="flex justify-between border-b border-indigo-900/40 pb-1">
                  <span className="text-white">{r.student_name}</span>
                  <span className="flex items-center gap-2">
                    <span className={r.score !== null ? 'text-emerald-300 font-bold' : 'text-amber-300'}>
                      {r.score !== null ? `${Number(r.score)}% \u2022 ${when(r.taken_at)}` : 'Pending'}
                    </span>
                    {role === 'admin' && r.score !== null && <button className="text-red-300 underline" onClick={() => deleteResult(q.id, r.student_id, r.student_name)}>Delete result</button>}
                  </span>
                </div>
              ))}
            </div>
          )}
        </div>
      ))}
    </div>
  );
};

export default QuizSection;
